"""Scene configs of the rapid-chirping training scenes (front-end ablation, round 2).

    uv run python experiments/ablation_scenarios/rapid_training/make_configs.py

The breakdown benchmark (``../``) tests chirp trains of 75-1000 ms, while every
training scene of train_v4 keeps the chirps of one fish at least 200 ms apart
(``min_interval_s = 0.2``, bursts with a median interval of 750 ms). For a fair
comparison of the front ends both detectors are retrained on train_v4 plus
scenes with rapid chirp trains. These configs are the train_v4 train and val
configs (same template splits, background recordings, fish population and
amplitude model) with only the chirp timing changed:

- spontaneous rate 0.3-1.0 chirps/s per fish (train_v4: 0.05-0.25),
- bursts of 5 chirps on average (train_v4: 2.2) whose centre-to-centre
  intervals are log-normal with median 110 ms and log SD 0.4 (5-95 %:
  ~57-210 ms; train_v4: 750 ms, 0.45),
- no minimum interval (train_v4: 0.2 s). The simulator still drops a chirp
  whose support would overlap the previous one of its fish (~70 ms for small
  templates), so the shortest intervals are ~70 ms, as in the benchmark.

Both families stay in (big chirps' long supports thin their own trains);
responses as in train_v4. Writes ``configs/train_v4_rapid_{train,val}.toml``.
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # experiments/: paths.py
from paths import REPO  # noqa: E402

OUT = Path(__file__).with_name("configs")
CHIRPS = {
    "rate_hz": [0.3, 1.0],
    "min_interval_s": 0.0,
    "burst_size_mean": 5.0,
    "burst_interval_s": [0.11, 0.4],
}
SEEDS = {"train": (40000, 40300), "val": (40300, 40340)}


def toml_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return repr(v)


def dump(cfg: dict, header: str) -> str:
    lines = [f"# {line}" if line else "#" for line in header.splitlines()]
    lines += [f"{k} = {toml_value(v)}" for k, v in cfg.items() if not isinstance(v, dict)]
    for section, values in cfg.items():
        if isinstance(values, dict):
            lines += ["", f"[{section}]"]
            lines += [f"{k} = {toml_value(v)}" for k, v in values.items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for split, (lo, hi) in SEEDS.items():
        base = tomllib.loads((REPO / f"configs/scenes/train_v4_{split}.toml").read_text())
        base["name"] = f"train_v4_rapid_{split}"
        base["chirps"].update(CHIRPS)
        header = (
            f"Rapid-chirping training scenes, {split} split (front-end ablation round 2).\n"
            f"Generated by experiments/ablation_scenarios/rapid_training/make_configs.py from\n"
            f"configs/scenes/train_v4_{split}.toml (chirp timing changed only); seeds {lo}:{hi}."
        )
        (OUT / f"train_v4_rapid_{split}.toml").write_text(dump(base, header))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
