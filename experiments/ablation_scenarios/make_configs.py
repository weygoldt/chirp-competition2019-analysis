"""Scene configs of the front-end breakdown benchmark (ablation_bench_v1).

    uv run python experiments/ablation_scenarios/make_configs.py

Two sweeps, each level one gridtools scene config, all derived from the
sim_v4 TEST config (configs/scenes/train_v4_test.toml: test-split chirp
templates of fish unseen in training, test-split real background recordings,
hybrid scenes, 60 s), changed only where the sweep needs it:

(a) ``df_<level>``: ΔEODf ramp-down. Two simulated fish, the second placed
    exactly ``level`` Hz above or below the first (``close_pair_prob = 1``,
    ``close_pair_df_hz = (level, level)``), no crossing and no random ramp;
    the calibrated individual drift (SD ~1 Hz, tau ~11 s) stays, so the
    instantaneous ΔF scatters around the level and every chirp is scored by
    its actual emitter ΔF. Chirp timing as in training, at the top of the
    training rate range (0.25 /s per fish).

(b) ``rate_<ms>``: chirp-rate ramp-up. Two simulated fish 40-80 Hz apart
    (a close pair at that distance, no crossing or ramp, so that assignment
    stays easy), small chirps only, in near-periodic trains:
    burst onsets Poisson at 1 chirp/s per fish / 8 chirps per burst, within a
    burst centre-to-centre intervals log-normal with median ``ms`` and log SD
    0.05; no minimum interval (training: 0.2 s) and no responses. The
    simulator still never lets one fish's chirp supports overlap (~70 ms for
    small templates), which sets the fastest level (75 ms, ~13 chirps/s);
    chirps that would overlap are dropped, so every chirp is scored by its
    actual interval to the neighbouring chirps of its fish.

Writes ``configs/*.toml`` and ``levels.json`` next to this script.
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # experiments/: paths.py
from paths import REPO  # noqa: E402

BASE = REPO / "configs/scenes/train_v4_test.toml"
OUT = Path(__file__).with_name("configs")

DF_LEVELS_HZ = [0.5, 1.0, 2.0, 3.0, 4.0, 6.0, 8.0, 12.0, 20.0]
DF_SCENES = 30
RATE_LEVELS_MS = [1000, 500, 300, 200, 150, 120, 100, 85, 75]
RATE_SCENES = 20


def toml_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return repr(v)


def dump(cfg: dict, header: str) -> str:
    lines = [f"# {line}" if line else "#" for line in header.splitlines()]
    top = {k: v for k, v in cfg.items() if not isinstance(v, dict)}
    lines += [f"{k} = {toml_value(v)}" for k, v in top.items()]
    for section, values in cfg.items():
        if isinstance(values, dict):
            lines += ["", f"[{section}]"]
            lines += [f"{k} = {toml_value(v)}" for k, v in values.items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    base = tomllib.loads(BASE.read_text())
    OUT.mkdir(exist_ok=True)
    levels = {"df": [], "rate": []}
    for k, df in enumerate(DF_LEVELS_HZ):
        cfg = json.loads(json.dumps(base))
        name = f"df_{df:04.1f}".replace(".", "p")
        cfg["name"] = f"ablation_bench_v1_{name}"
        cfg["population"] = {
            "n_fish": [2, 2],
            "close_pair_prob": 1.0,
            "close_pair_df_hz": [df, df],
            "crossing_prob": 0.0,
            "ramp_prob": 0.0,
        }
        cfg["chirps"]["rate_hz"] = [0.25, 0.25]
        seeds = (20000 + 100 * k, 20000 + 100 * k + DF_SCENES)
        header = (
            f"Front-end breakdown benchmark v1, sweep (a) ΔEODf: level {df} Hz.\n"
            "Generated by experiments/ablation_scenarios/make_configs.py from\n"
            f"configs/scenes/train_v4_test.toml; seeds {seeds[0]}:{seeds[1]}."
        )
        (OUT / f"{name}.toml").write_text(dump(cfg, header))
        levels["df"].append({"name": name, "level_hz": df, "seeds": list(seeds)})
    for k, ms in enumerate(RATE_LEVELS_MS):
        cfg = json.loads(json.dumps(base))
        name = f"rate_{ms:04d}ms"
        cfg["name"] = f"ablation_bench_v1_{name}"
        # the two fish 40-80 Hz apart, never crossing: assignment stays easy,
        # so the sweep isolates chirp density
        cfg["population"] = {
            "n_fish": [2, 2],
            "close_pair_prob": 1.0,
            "close_pair_df_hz": [40.0, 80.0],
            "crossing_prob": 0.0,
            "ramp_prob": 0.0,
        }
        cfg["chirps"].update(
            {
                "families": ["small"],
                "rate_hz": [1.0, 1.0],
                "min_interval_s": 0.0,
                "burst_size_mean": 8.0,
                "burst_interval_s": [ms / 1000.0, 0.05],
                "response_prob": 0.0,
            }
        )
        seeds = (30000 + 100 * k, 30000 + 100 * k + RATE_SCENES)
        header = (
            f"Front-end breakdown benchmark v1, sweep (b) chirp rate: trains at {ms} ms.\n"
            "Generated by experiments/ablation_scenarios/make_configs.py from\n"
            f"configs/scenes/train_v4_test.toml; seeds {seeds[0]}:{seeds[1]}."
        )
        (OUT / f"{name}.toml").write_text(dump(cfg, header))
        levels["rate"].append({"name": name, "interval_ms": ms, "seeds": list(seeds)})
    (OUT.parent / "levels.json").write_text(json.dumps(levels, indent=1) + "\n")
    print(f"wrote {len(levels['df']) + len(levels['rate'])} configs to {OUT}")


if __name__ == "__main__":
    main()
